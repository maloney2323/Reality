/* Reality auto-diagnostic handoff from a failed Run Full Loop click.
   The button delegates investigation, never installation or original-job replay.
   Failures are client observations until separately verified by the provider. */
(()=>{
'use strict';
const WORK=/^work:[a-f0-9]{32}$/;
const UUID=/^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}$/i;
const CODE=/^[A-Z][A-Z0-9_]{3,110}$/;
const STAGES=new Set(['OWNER_LEDGER_READBACK','NEW_WORK_DISCOVERY','WORKER_DISPATCH','OWNER_INSTALL_PREFLIGHT','ORIGINAL_CONTINUITY','LOOP_START','NO_ELIGIBLE_NEW_WORK']);
const seen=new Set();
const byId=id=>document.getElementById(id);
function paint(text){
 const root=byId('realityChatAutomationDiagnostics');
 const status=byId('realityChatAutomationDiagnosticStatus');
 if(root)root.hidden=false;
 if(status)status.textContent=text;
}
function verifyAudit(data){
 return data?.ok===true&&data?.status==='GOVERNED_AUDIT_RECORDED'&&
   data.review_only===true&&data.installation_authorized===false&&
   data.job_started===false&&data.production_changed===false&&
   data.audit_executed===true;
}
window.realityHandoffFullLoopFailure=async function(detail){
 const stage=STAGES.has(detail?.stage)?detail.stage:'LOOP_START';
 const code=CODE.test(String(detail?.code||''))?String(detail.code):'UNCLASSIFIED_AUTOMATION_BLOCKER';
 const work=WORK.test(String(detail?.original_work_id||''))?detail.original_work_id:null;
 const conversation=typeof window.realityActiveConversationId==='function'?
   window.realityActiveConversationId():null;
 if(typeof window.homeOwnerSignedIn!=='function'||
    window.homeOwnerSignedIn()!==true||!UUID.test(String(conversation||''))){
   paint('Sign in and select a saved Reality conversation before this diagnostic can be recorded. No repair work was started.');
   return {status:'OWNER_CONTEXT_REQUIRED'};
 }
 const key=[conversation,work||'NO_JOB',stage,code].join('|');
 if(seen.has(key))return {status:'EXISTING_DIAGNOSTIC_NOT_REPEATED'};
 seen.add(key);
 if(typeof window.realityOpenChatDock==='function')window.realityOpenChatDock(false);
 paint('Reality detected '+code+'. Checking provider evidence and opening an owner-scoped diagnostic conversation. No installation authorized.');
 // Only the already-governed read-only provider audit is launched. This audit
 // cannot install, authorize a new original job or change production.
 const auditPromise=(async()=>{
  try{
   const r=await fetch('/api/reality/personal-capability-discovery-audit',{
    method:'POST',credentials:'same-origin',cache:'no-store',
    headers:{'content-type':'application/json'},
    body:JSON.stringify({intent:'RUN_GOVERNED_CAPABILITY_DISCOVERY_AUDIT'})
   });
   const result=await r.json().catch(()=>null);
   return r.ok&&verifyAudit(result)?'VERIFIED_READ_ONLY_AUDIT_RECORDED':
      'AUDIT_UNAVAILABLE_NOT_A_REPAIR';
  }catch{return 'AUDIT_UNAVAILABLE_NOT_A_REPAIR'}
 })();
 // This delegated, explicitly LABELED automation report is ordinary chat.
 // The chat server enforces owner authentication and grants no execution authority.
 // Never put this in the unsent customer prompt or set an active-goal command.
 const report=[
  '[REALITY AUTOMATION DIAGNOSTIC — generated by the Run Full Loop button, not typed by the owner]',
  'Observed UI stage: '+stage,
  'Observed error/status code: '+code,
  'Original work: '+(work||'NONE_VERIFIED'),
  'Evidence status: CLIENT_OBSERVATION_AWAITING_INDEPENDENT_SERVER_READBACK.',
  'Investigate the exact source of this blocker using independently available evidence.',
  'Explain what is verified versus still unknown, classify the problem and the next safe test.',
  'Do not assume a missing capability, claim a repair, create work, change a goal or authorize installation.',
  'A separate read-only governed discovery audit was requested. Its outcome is not yet verified here.',
  'If new code or execution authority is needed, it must go through Reality’s exact governed worker and Chat approval gate.'
 ].join('\\n');
 const chatPromise=(async()=>{
  try{
   const r=await fetch('/api/reality/personal-chat',{
    method:'POST',credentials:'same-origin',cache:'no-store',
    headers:{'content-type':'application/json'},
    body:JSON.stringify({conversation_id:conversation,request_id:crypto.randomUUID(),message:report})
   });
   const data=await r.json().catch(()=>null);
   if(!r.ok||data?.ok!==true||data.conversation_id!==conversation||
       data.continuity?.current_answer_persisted!==true)
    return 'CHAT_DIAGNOSIS_NOT_DURABLY_VERIFIED';
   if(typeof window.realityChatRefreshTranscript==='function')
    await window.realityChatRefreshTranscript().catch(()=>{});
   if(typeof window.realityChatRefreshEvents==='function')
    void window.realityChatRefreshEvents();
   return 'CHAT_DIAGNOSIS_PERSISTED';
  }catch{return 'CHAT_DIAGNOSIS_NOT_DURABLY_VERIFIED'}
 })();
 const [audit,chat]=await Promise.all([auditPromise,chatPromise]);
 const auditOk=audit==='VERIFIED_READ_ONLY_AUDIT_RECORDED';
 const chatOk=chat==='CHAT_DIAGNOSIS_PERSISTED';
 paint((chatOk?'Reality’s diagnostic conversation is saved.':
   'Reality could not verify a saved diagnostic response. Do not retry an uncertain operation automatically.')+
   ' '+(auditOk?'Independent discovery audit recorded for review.':
     'Independent discovery audit unavailable or unverified.')+
   ' No repair, installation or final settlement is being claimed.');
 return {status:chatOk?'DIAGNOSTIC_CHAT_RECORDED':'DIAGNOSTIC_CHAT_UNVERIFIED',
  audit_status:audit,original_work_id:work,installation_authorized:false};
};
})();
