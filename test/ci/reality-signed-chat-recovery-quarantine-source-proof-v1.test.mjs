import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const sha=/^[a-f0-9]{40}$/;
const uuid=/^[a-f0-9]{8}-(?:[a-f0-9]{4}-){3}-[a-f0-9]{12}$/i;
const work=/^work:[a-f0-9]{32}$/;
const hash=/^sha256:[a-f0-9]{64}$/;
const allowed=/^(?:src\/[A-Za-z0-9_./-]+\.js|api\/reality\/[A-Za-z0-9_./-]+\.js|reality-[A-Za-z0-9_.-]+\.(?:js|css)|index\.html)$/;
const read=(commit,path)=>execFileSync('git',['show',commit+':'+path],{encoding:'utf8',timeout:14000,maxBuffer:500000});
const git=(args)=>execFileSync('git',args,{encoding:'utf8',timeout:14000,maxBuffer:500000}).trim();
const [base,head,branch]=[process.env.BASE_SHA,process.env.HEAD_SHA,process.env.PR_HEAD_BRANCH];
test('independent quarantine source matches only signed original and precise frozen change',()=>{
 assert.match(base||'',sha);assert.match(head||'',sha);
 assert.match(branch||'',/^reality\/chat-recovery\/[a-f0-9-]{36}$/);
 assert.equal(git(['rev-parse','HEAD']),head);
 const trigger=branch.slice('reality/chat-recovery/'.length);
 assert.match(trigger,uuid);
 const artifact='evidence/reality-chat-recovery/'+trigger+'.json';
 const proof=JSON.parse(read(head,artifact));
 assert.equal(proof.version,'reality-signed-chat-recovery-quarantined-candidate-v1');
 assert.equal(proof.trigger_id,trigger);
 assert.match(proof.original_work_id,work);
 assert.match(proof.source_sha256,/^[a-f0-9]{64}$/);
 assert.match(proof.recovery_spec_sha256,hash);
 assert.match(proof.blocker_receipt_sha256,hash);
 assert.match(proof.candidate_sha256,hash);
 assert.equal(proof.source_installed,false);
 assert.equal(proof.independent_ci_verified,false);
 assert.equal(proof.feature_acceptance_verified,false);
 assert.equal(proof.installation_authorized,false);
 assert.equal(proof.original_job_completed,false);
 assert.equal(proof.production_changed,false);
 assert.equal(proof.new_shift_started,false);
 const c=proof.candidate;
 assert.equal(c.spec_sha256,proof.recovery_spec_sha256);
 assert.equal(c.blocker_receipt_sha256,proof.blocker_receipt_sha256);
 assert.equal(c.original_work_id,proof.original_work_id);
 assert.equal(c.base_sha,base);
 assert.ok(allowed.test(c.target_path)&&!c.target_path.includes('..')&&!c.target_path.includes('//'));
 assert.equal(git(['rev-list','--count',base+'..'+head]),'2');
 const files=git(['diff','--name-only',base,head]).split('\n').sort();
 assert.deepEqual(files,[artifact,c.target_path].sort());
 const parent=git(['rev-parse',head+'^']);
 assert.equal(git(['rev-parse',parent+'^']),base);
 assert.deepEqual(git(['diff','--name-only',parent,head]).split('\n'),[artifact]);
 assert.deepEqual(git(['diff','--name-only',base,parent]).split('\n'),[c.target_path]);
 const before=read(base,c.target_path),after=read(head,c.target_path);
 const first=before.indexOf(c.find);
 assert.ok(first>=0);
 assert.equal(before.indexOf(c.find,first+1),-1);
 assert.equal(before.slice(0,first)+c.replace+before.slice(first+c.find.length),after);
 const hex=x=>createHash('sha1').update('blob '+Buffer.byteLength(x)+'\0').update(x).digest('hex');
 assert.equal(hex(before),c.source_blob_sha);
 if(c.target_path.endsWith('.js')){
  assert.doesNotThrow(()=>execFileSync('node',['--check',c.target_path],
    {timeout:12000,encoding:'utf8'}));
 }
});
