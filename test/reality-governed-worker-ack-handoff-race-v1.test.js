import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const sql=read('sql/reality-governed-worker-dispatch-race-v1.sql');
const edge=read('supabase/functions/reality-governed-worker-life-v1/index.ts');
const script=read('scripts/reality-governed-worker-proof-of-life-v1.mjs');
test('signed worker dispatch state is service-only and read-only',()=>{
 assert.match(sql,/CREATE OR REPLACE FUNCTION public\.reality_check_governed_worker_dispatch_v1/);
 assert.match(sql,/SECURITY INVOKER/);
 assert.match(sql,/current_user <> 'service_role'/);
 assert.match(sql,/WHERE approval_id=p_approval_id/);
 assert.match(sql,/w\.dispatch_fence IS DISTINCT FROM p_fence/);
 assert.match(sql,/w\.dispatch_lease_expires_at<=clock_timestamp/);
 assert.match(sql,/w\.target_environment<>'ISOLATED_PREVIEW'/);
 assert.match(sql,/w\.wake_state='DISPATCH_CLAIMED'/);
 assert.match(sql,/w\.wake_state IN \('DISPATCH_ACCEPTED','WORKER_ALIVE'\)/);
 assert.match(sql,/REVOKE ALL ON FUNCTION public\.reality_check_governed_worker_dispatch_v1/);
 assert.match(sql,/FROM PUBLIC,anon,authenticated/);
 assert.doesNotMatch(sql,/\b(?:INSERT INTO|DELETE FROM|UPDATE reality_internal)\b/);
});
test('only OIDC-authenticated identity may receive a narrowly scoped 425',()=>{
 const verify=edge.indexOf('await verifySignedRunner(jwt,providerToken)');
 const inspect=edge.indexOf("reality_check_governed_worker_dispatch_v1");
 const mutation=edge.indexOf("reality_ack_governed_worker_alive_v1");
 assert.ok(verify>=0&&inspect>verify&&mutation>inspect);
 assert.match(edge,/body\.action==='alive'/);
 assert.match(edge,/DISPATCH_RECEIPT_PENDING/);
 assert.match(edge,/SIGNED_WORKER_AWAITING_DELIVERY_RECEIPT/);
 assert.match(edge,/oidc_verified:true/);
 assert.match(edge,/worker_started:true,installation_performed:false/);
 assert.match(edge,/execution_authorized:false/);
 assert.match(edge,/FENCED_DISPATCH_NOT_CURRENT/);
 assert.match(edge,/,425\)/);
});
test('node worker only retries an exact signed 425, never errors or arbitrary approvals',()=>{
 const file=new URL('../scripts/reality-governed-worker-proof-of-life-v1.mjs',import.meta.url).pathname;
 const run=spawnSync(process.execPath,['--check',file],{encoding:'utf8'});
 assert.equal(run.status,0,run.stderr);
 assert.match(script,/response\.status===425/);
 assert.match(script,/proof\.oidc_verified===true/);
 assert.match(script,/proof\.exact_approval_id===wake\.approval_id/);
 assert.match(script,/proof\.dispatch_fence===wake\.dispatch_fence/);
 assert.match(script,/proof\.installation_performed===false/);
 assert.match(script,/proof\.production_changed===false/);
 assert.match(script,/UNVERIFIED_DELIVERY_PENDING_RESPONSE/);
 assert.match(script,/SIGNED_DELIVERY_RECEIPT_TIMEOUT_NO_INSTALL/);
 assert.match(script,/if\(!signedLife\)fail/);
 const life=script.indexOf("await callBroker('alive')");
 const ready=script.indexOf("await callBroker('ready')");
 const output=script.indexOf("setReady('true')");
 assert.ok(life>=0&&ready>life&&output>ready);
 assert.doesNotMatch(script,/reality_owner_approve_qualified_preview_v1/);
 assert.doesNotMatch(script,/GITHUB_EVENT_NAME.*workflow_dispatch/);
});
