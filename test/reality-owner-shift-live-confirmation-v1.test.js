test('activity readback is owned by current signed-in user and inaccessible to normal browser roles',()=>{
 const api=source('api/reality/personal-governed-employee-shift.js');
 const rpc=source('src/reality-governed-shift-boundary-v1.js');
 const sql=source('supabase/migrations/20261108_owner_shift_live_activity_receipts_v1.sql');
 assert.match(api,/p_owner_id:session\.user_id,p_shift_id:chosen\.shift_id/);
 assert.match(api,/shift_activity_status='VERIFIED_OWNER_ACTIVITY'/);
 assert.match(api,/ACTIVITY_READBACK_UNAVAILABLE/);
 assert.match(rpc,/read_owner_shift_live_activity_v1/);
 assert.match(rpc,/record_current_shift_worker_pulse_v1/);
 assert.match(sql,/current_user<>'service_role'/);
 assert.match(sql,/s\.owner_id=p_owner_id and s\.shift_id=p_shift_id/);
 assert.match(sql,/last_worker_completed_at/);
 assert.match(sql,/source_events/);
 assert.match(sql,/original_jobs/);
 assert.match(sql,/revoke all on function public\.reality_read_owner_shift_live_activity_v1/);
 assert.match(sql,/from public,anon,authenticated/);
 assert.doesNotMatch(sql,/grant execute[^;]*to authenticated/);
});

